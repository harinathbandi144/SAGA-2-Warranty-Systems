CREATE TABLE claim_schema.claim_status_history (
                                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                   claim_id BIGINT NOT NULL,
                                                   old_status VARCHAR(30) NOT NULL,
                                                   new_status VARCHAR(30) NOT NULL,
                                                   changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                                   CONSTRAINT fk_claim_status_history_claim
                                                       FOREIGN KEY (claim_id)
                                                           REFERENCES claim_schema.claims(id)
);

CREATE INDEX idx_claim_status_history_claim_id
    ON claim_schema.claim_status_history(claim_id);